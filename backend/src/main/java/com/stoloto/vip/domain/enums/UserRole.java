package com.stoloto.vip.domain.enums;

/**
 * Роли пользователей в системе
 */
public enum UserRole {
    GUEST,        // Неавторизованный пользователь
    USER,         // Обычный игрок
    MODERATOR,    // Модератор (просмотр логов)
    ADMIN,        // Администратор (настройка комнат, ботов, бустов)
    SUPER_ADMIN   // Полный доступ включая управление ролями
}
